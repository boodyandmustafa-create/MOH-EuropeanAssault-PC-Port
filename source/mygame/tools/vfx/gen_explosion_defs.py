"""Collects the particle definition names of explosions from every level's level_a.str and writes src/explosion_defs.h
(names relative to vfx\\, hashed at run time like the impact defs). Usage: python gen_explosion_defs.py"""
import glob, re, os

root = r'C:\Users\nsr\Downloads\xboxrecomp-0.16.0\mygame'
names = set()
for f in glob.glob(os.path.join(root, 'game', 'DATA', '*', '*', 'level_a.str')):
    data = open(f, 'rb').read()
    for m in re.finditer(rb'[Vv][Ff][Xx].[Dd]efinitions.[A-Za-z0-9_\\]*\.xdd', data):
        s = m.group().decode('latin1')
        names.add(s[4:].replace('/', chr(92)))            # after "VFX" + separator; one separator style (backslash)
keys = re.compile(r'grenade|exp[_0-9]|exp\.|bomb|shockwave|blastshrap|dustball|fieryblast|fireball|democharge|artillery|mortar|boom|blow|detcord', re.I)
skip = re.compile(r'muzzle|trail|exhaust|smoke_?far|farsmoke', re.I)
sel = sorted(n for n in names if keys.search(n) and not skip.search(n))
out = os.path.join(root, 'src', 'explosion_defs.h')
with open(out, 'w') as o:
    o.write('/* generated by tools/vfx/gen_explosion_defs.py: particle definition files of explosions */\n')
    o.write('static const char *const k_explosion_defs[] = {\n')
    for n in sel:
        o.write('    "%s",\n' % n.replace('\\', '\\\\'))
    o.write('};\n')
print(len(names), 'definitions seen,', len(sel), 'explosion ones ->', out)
print(' '.join(s.split('\\')[-1][:-4] for s in sel))
