"""Collects the particle definition files of rain / weather (prefabs whose name has 'rain' or 'weather', not the desert
dust ones) from every level_a.str and writes src/weather_defs.h (names relative to vfx\\, hashed at run time like the
explosion defs). Usage: python gen_weather_defs.py"""
import glob, re, os

root = r'C:\Users\nsr\Downloads\xboxrecomp-0.16.0\mygame'
names = set()
pat = re.compile(rb'file:.z:.moh4.data.shared.vfx.(prefabs.[A-Za-z0-9_\\/]*(?:rain|weather)[A-Za-z0-9_]*\.xdd)', re.I)
for f in glob.glob(os.path.join(root, 'game', 'DATA', '*', '*', 'level_a.str')):
    data = open(f, 'rb').read()
    for m in pat.finditer(data):
        s = m.group(1).decode('latin1').replace('/', chr(92))
        if 'dust' in s.lower() or 'prefabs' + chr(92) + 'bob' in s.lower():     # desert dust; Battle of the Bulge = snow, not rain
            continue
        names.add(s)
sel = sorted(names, key=str.lower)
out = os.path.join(root, 'src', 'weather_defs.h')
with open(out, 'w') as o:
    o.write('/* generated by tools/vfx/gen_weather_defs.py: particle definition files of rain / weather prefabs */\n')
    o.write('static const char *const k_weather_defs[] = {\n')
    for n in sel:
        o.write('    "%s",\n' % n.replace('\\', '\\\\'))
    o.write('};\n')
print(len(sel), 'weather definitions ->', out)
print('\n'.join(sel))
