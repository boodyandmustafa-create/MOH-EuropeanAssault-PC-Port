import struct

VIV = r'C:\Users\nsr\Downloads\xboxrecomp-0.16.0\mygame\game\DATA\SHARED\UI\FE\mohfe.viv'
OUT = r'C:\Users\nsr\Downloads\xboxrecomp-0.16.0\xboxrecomp-0.16.0\src\kernel\icon_table.h'
sheets = {'helpBar': (28316564, 115584), 'cafela_helpbar': (457388, 110720)}
# xsh entry name -> (console control index in IC_ order, label)
WANT = {
    '5': (0, 'A'), '7': (0, 'A'),
    '12': (1, 'B'), '14': (1, 'B'),
    '19': (2, 'X'),
    '26': (3, 'Y'),
    '54': (4, 'Black'),
    '47': (5, 'White'), '61': (5, 'White(small)'),
    '40': (6, 'LT'),
    '33': (7, 'RT'),
}

def fnv(b):
    h = 0xCBF29CE484222325
    for c in b:
        h = ((h ^ c) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h

d = open(VIV, 'rb').read()
rows = {}
for sname, (off, sz) in sheets.items():
    b = d[off:off + sz]
    cnt = struct.unpack('>I', b[8:12])[0]
    p = 16
    ent = {}
    for i in range(cnt):
        o, s = struct.unpack('>II', b[p:p + 8])
        e = b.index(b'\0', p + 8)
        ent[b[p + 8:e].decode()] = (o, s)
        p = e + 1
    xo, xs = [v for k, v in ent.items() if k.endswith('.xsh')][0]
    x = b[xo:xo + xs]
    n = struct.unpack('<I', x[8:12])[0]
    for i in range(n):
        q = 16 + i * 8
        nm = x[q:q + 4].decode().strip()
        o = struct.unpack('<I', x[q + 4:q + 8])[0]
        w, h = struct.unpack('<HH', x[o + 4:o + 8])
        if nm in WANT and x[o] == 0x61:
            data = x[o + 0x10:o + 0x10 + w * h]
            hv = fnv(data)
            rows.setdefault(hv, (w, h, WANT[nm][0], '%s:%s(%s)' % (sname, nm, WANT[nm][1])))
lines = ['/* generated by scratchpad/gen_icon_table.py from the front-end icon sheets: FNV-1a 64 of the first\n * mip of each Xbox button icon (DXT3), the console control it stands for */']
lines.append('static const struct { uint64_t hash; uint16_t w, h; uint8_t ic; const char *name; } k_icon_tab[] = {')
for hv, (w, h, ic, nm) in rows.items():
    lines.append('    { 0x%016XULL, %d, %d, %d, "%s" },' % (hv, w, h, ic, nm))
lines.append('};')
open(OUT, 'w').write('\n'.join(lines) + '\n')
print(len(rows), 'entries')
for hv, v in rows.items():
    print('%016x' % hv, v)
